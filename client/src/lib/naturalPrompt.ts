/**
 * **사람이 적은 말을 프롬프트 말로 바꿉니다.**
 *
 * 맞는 말입니다. 「비를 추가해」 라고 적으면 안 된다고 **안내문에 적어 두는 것**은
 * 규칙을 사람에게 떠넘기는 것입니다. 적는 사람은 연출을 생각하지 프롬프트 문법을
 * 생각하지 않습니다.
 *
 * # 두 갈래로 나눕니다
 *
 * · **여기(규칙)** — LLM 없이, 즉시, 틀릴 수 없는 것만. 명령형 말꼬리를 평서형으로.
 * API 키가 없어도 돌고, 기다림이 없습니다.
 * · **LLM** — 뜻을 알아야 하는 것. 「슬프게」 를 「시선이 내려가고 입술이 다물린다」 로
 * 바꾸는 일은 규칙으로 못 합니다. 요청문이 그렇게 시킵니다(`_공통규칙.md`).
 *
 * # 왜 규칙 쪽을 «틀릴 수 없는 것» 으로 좁히나
 *
 * 사람이 적은 글을 기계가 고치면, 고친 것이 틀렸을 때 **원래 뜻이 사라집니다.**
 * 그래서 여기서는 «말꼬리만» 만집니다 — 낱말과 순서는 그대로 둡니다. 뜻이 바뀌지
 * 않는 변환만 합니다.
 */

/**
 * 명령형 말꼬리 → 평서형.
 *
 * 왜 고치나: 「바꿔·지워·빼·늘려·추가해」 같은 말이 프롬프트 본문에 들어가면, 일부
 * 영상 모델이 그 어투를 보고 **«새로 만들기» 가 아니라 «영상 편집·연장» 작업으로
 * 오인합니다.** 그러면 엉뚱한 결과가 나오는데, 적은 사람은 까닭을 알 수가 없습니다.
 *
 * 앞의 목적어를 살려 그대로 씁니다 — 「비를 추가해」 → 「비가 있다」.
 */

/**
 * 받침이 있으면 «이», 없으면 «가». 한국어 조사는 앞 글자의 받침이 정합니다.
 *
 * 2026-09-18 첫 판은 「이(가)」 를 그대로 박아서 「비 이(가) 있다」 가 나왔습니다.
 * 사람이 읽을 글인데 괄호가 남으면 안 됩니다.
 */
function josa(word: string, withBatchim: string, without: string): string {
  const last = word.trim().slice(-1);
  const code = last.charCodeAt(0);
  // 한글 음절이 아니면(숫자·영문) 받침이 있는 쪽으로 둡니다 — 「ref_img_1 이」 가 자연스럽습니다.
  if (Number.isNaN(code) || code < 0xac00 || code > 0xd7a3) return withBatchim;
  return (code - 0xac00) % 28 ? withBatchim : without;
}

/**
 * 명령형 말꼬리 → 평서형.
 *
 * 왜 고치나: 「바꿔·지워·빼·늘려·추가해」 같은 말이 프롬프트 본문에 들어가면, 일부
 * 영상 모델이 그 어투를 보고 **«새로 만들기» 가 아니라 «영상 편집·연장» 작업으로
 * 오인합니다.** 그러면 엉뚱한 결과가 나오는데, 적은 사람은 까닭을 알 수가 없습니다.
 *
 * **목적어를 통째로 살립니다.** 2026-09-18 첫 판은 「불꽃을 크게 키워」 에서 부사
 * 「크게」 를 목적어로 잡아 「불꽃을 크게 이(가) 크게 보인다」 를 만들었습니다.
 * 그래서 이제 **조사(을·를·으로·로)를 반드시 끼고** 그 앞을 목적어로 봅니다.
 */
const ORDERS: { find: RegExp; make: (target: string, extra?: string) => string }[] = [
  // 「~를 (부사) 추가해 / 넣어 / 더해」 → 「~가 있다」
  {
    find: /(\S+?)(?:을|를)\s*(?:\S+\s+)?(?:추가해|추가하고|추가|넣어|넣고|더해|더하고)(?:줘|주세요|라)?(?=[\s,.!?]|$)/g,
    make: (target) => `${target}${josa(target, "이", "가")} 있다`,
  },
  // 「~를 (부사) 빼 / 지워 / 없애」 → 「~가 없다」
  {
    /*
      조사를 **안 붙이고** 적는 일이 잦습니다 — 「간판 지워줘」. 그래서 조사는 있어도
      없어도 받되, 앞말은 **한 낱말만** 봅니다(공백 앞까지). 그래야 「배경에서 간판
      지워줘」 에서 「배경에서」 까지 삼키지 않습니다.
    */
    /*
      **맨몸 동사는 문장 끝에서만** 봅니다. 「담배를 빼 문다」 처럼 뒤에 다른 말이
      이어지면 그건 명령이 아니라 겹동사입니다(2026-09-18 시험에서 실제로 걸렸습니다).
      「빼줘」·「지워줘」 처럼 청유가 붙은 꼴은 뒤에 말이 와도 명령이 맞습니다.
    */
    find: /([^\s]+?)(?:은|는|을|를)?\s*(?:(?:빼줘|빼고|지워줘|지우고|없애고|삭제해)(?:주세요|라)?(?=[\s,.!?]|$)|(?:빼|지워|없애)(?:주세요|라)?(?=[,.!?]|$))/g,
    make: (target) => `${target}${josa(target, "이", "가")} 없다`,
  },
  // 「~를 크게 해 / 키워」 → 「~가 크게 보인다」. 부사를 목적어로 잡지 않게 조사를 끼고 봅니다.
  {
    find: /(\S+?)(?:을|를)\s*(?:크게\s*해|크게\s*키워|키워|키우고)(?:줘|주세요|라)?(?=[\s,.!?]|$)/g,
    make: (target) => `${target}${josa(target, "이", "가")} 크게 보인다`,
  },
  // 「A 를 B 로 바꿔」 → 「A 는 B 다」. 앞의 목적어를 버리지 않습니다.
  {
    find: /(\S+?)(?:을|를)\s*(\S+?)(?:으로|로)\s*(?:바꿔|바꾸고|변경해)(?:줘|주세요|라)?(?=[\s,.!?]|$)/g,
    make: (target, extra) =>
      `${target}${josa(target, "은", "는")} ${extra}${josa(extra ?? "", "이다", "다")}`,
  },
  // 목적어 없이 「B 로 바꿔」 만 적은 경우.
  {
    find: /(?<![을를]\s*\S*)(\S+?)(?:으로|로)\s*(?:바꿔|바꾸고|변경해)(?:줘|주세요|라)?(?=[\s,.!?]|$)/g,
    make: (target) => `${target}${josa(target, "이다", "다")}`,
  },
];

/** 이 글에 명령형이 섞였는가. 고치기 전에 «고칠 것이 있나» 를 묻는 데 씁니다. */
export function hasOrders(text: string): boolean {
  return ORDERS.some((rule) => {
    rule.find.lastIndex = 0;
    return rule.find.test(text);
  });
}

/**
 * 명령형을 평서형으로 바꿉니다. **낱말과 순서는 그대로** 둡니다.
 *
 * 바꾼 것이 있으면 무엇을 바꿨는지 함께 돌려줍니다 — 말없이 고치면
 * 「내가 적은 것과 다른데」 가 됩니다.
 */
export function plainify(text: string): { text: string; changed: string[] } {
  const changed: string[] = [];
  let out = text;
  for (const rule of ORDERS) {
    out = out.replace(rule.find, (whole, target: string, extra?: string) => {
      const next = rule.make(target, typeof extra === "string" ? extra : undefined);
      changed.push(`${whole.trim()} → ${next}`);
      return next;
    });
  }
  return { text: out, changed };
}

/**
 * **감정 이름만 적혀 있는가.**
 *
 * 생성기는 감정을 모릅니다. 눈에 보이는 신호만 압니다. 「슬프게」 만 적으면 대개
 * 아무 일도 일어나지 않는 기본 얼굴이 나옵니다.
 *
 * 여기서 **고치지는 않습니다** — 어떤 신호를 붙일지는 연출의 몫이라 기계가 정하면
 * 안 됩니다. 대신 «신호가 없다» 를 알려 주고 보기를 제안합니다.
 */
const FEELINGS: Record<string, string> = {
  슬프: "시선이 내려가고 입술이 다물린다",
  화: "턱에 힘이 들어가고 미간이 좁아진다",
  놀라: "눈이 커지고 숨이 한 박자 멎는다",
  기쁘: "입꼬리가 올라가고 눈가가 접힌다",
  무서: "어깨가 올라가고 눈을 덜 깜빡인다",
  긴장: "손이 가만히 멈추고 어깨가 굳는다",
  지쳐: "어깨가 처지고 천천히 깜빡인다",
  담담: "얼굴은 그대로 두고 손만 움직인다",
};

/** 눈에 보이는 신호를 나타내는 말. 하나라도 있으면 «신호가 있다» 로 봅니다. */
const SIGNALS = /눈|시선|입|입술|턱|눈썹|어깨|손|고개|숨|미간|볼|깜빡|주먹|목|허리|발/;

export function missingSignal(text: string): { hint: string; example: string } | null {
  if (!text.trim()) return null;
  if (SIGNALS.test(text)) return null;
  const hit = Object.keys(FEELINGS).find((word) => text.includes(word));
  if (!hit) return null;
  return {
    hint: "감정 이름만 적혀 있습니다. 생성기는 감정을 모르고 **눈에 보이는 신호**만 압니다.",
    example: FEELINGS[hit],
  };
}
